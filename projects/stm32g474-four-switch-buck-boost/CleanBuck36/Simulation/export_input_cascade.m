function export_input_cascade
% Exact factored coefficients from the accepted linear design. No hardware IO.
root=fileparts(mfilename('fullpath'));
r=jsondecode(fileread(fullfile(root,'Results','input-cascade','linear-design.json')));
assert(r.linearDesignPass);i=r.innerSelected;v=r.outerSelected;
out=fullfile(root,'CurrentCascade');if ~isfolder(out),mkdir(out);end
s=tf('s');w=2*pi*i.notchHz;
n=c2d((s^2+2*i.notchZeroDamping*w*s+w^2)/(s^2+2*i.notchPoleDamping*w*s+w^2),r.innerSample_s,'tustin');
[b,a]=tfdata(n,'v');
fid=fopen(fullfile(out,'cascade_coefficients.h'),'w');assert(fid>=0);
fprintf(fid,'/* Generated by export_input_cascade.m; simulation only. */\n#ifndef CASCADE_COEFFICIENTS_H\n#define CASCADE_COEFFICIENTS_H\n');
names={'CURRENT_KP','CURRENT_KI','VOLTAGE_KP','VOLTAGE_KI'};values=[i.kp i.ki v.kp v.ki];
for k=1:numel(names),fprintf(fid,'#define %s %.12ef\n',names{k},values(k));end
for pair={ {'CURRENT',i.poleHz,r.innerSample_s},{'VOLTAGE',v.poleHz,r.outerSample_s} }
 p=pair{1};wt=2*pi*p{2}*p{3};
 fprintf(fid,'#define %s_LP_A %.12ef\n#define %s_LP_B %.12ef\n',p{1},(2-wt)/(2+wt),p{1},wt/(2+wt));
end
for k=1:3,fprintf(fid,'#define NOTCH_B%d %.12ef\n',k-1,b(k));end
for k=2:3,fprintf(fid,'#define NOTCH_A%d %.12ef\n',k-1,a(k));end
fprintf(fid,'#endif\n');fclose(fid);
end
